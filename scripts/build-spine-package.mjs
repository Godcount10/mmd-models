#!/usr/bin/env node

import { readFile, writeFile } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = fileURLToPath(new URL('..', import.meta.url))
const MODEL_DIR = join(ROOT, 'models', 'nikke-rupee-winter-shopper', '1.0.0')
const MODEL_ID = 'nikke-rupee-winter-shopper'

const skeleton = await readFile(join(MODEL_DIR, 'c203_00.skel'))
const atlas = await readFile(join(MODEL_DIR, 'c203_00.atlas'))
const encode = (bytes) => bytes.toString('base64')
const dataUri = (mime, bytes) => `data:${mime};base64,${encode(bytes)}`

const source = `/* Generated by scripts/build-spine-package.mjs. Do not edit manually. */
(() => {
  const packages = globalThis.__MMD_SPINE_PACKAGES__ ??= Object.create(null)
  packages[${JSON.stringify(MODEL_ID)}] = {
    skeleton: ${JSON.stringify(dataUri('application/octet-stream', skeleton))},
    atlas: ${JSON.stringify(dataUri('text/plain;charset=utf-8', atlas))},
  }
})()
`

await writeFile(join(MODEL_DIR, 'model.js'), source, 'utf8')
console.log(`Generated ${join(dirname(MODEL_DIR), '1.0.0', 'model.js')}`)
console.log(`Skeleton: ${skeleton.byteLength} bytes; atlas: ${atlas.byteLength} bytes; package: ${Buffer.byteLength(source, 'utf8')} bytes`)
